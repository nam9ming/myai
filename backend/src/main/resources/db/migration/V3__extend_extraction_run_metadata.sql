ALTER TABLE extraction_runs
    MODIFY provider VARCHAR(100) NULL,
    MODIFY model VARCHAR(100) NULL,
    ADD model_version VARCHAR(100),
    ADD schema_version VARCHAR(100),
    ADD preprocessing_version VARCHAR(100),
    ADD execution_mode VARCHAR(32),
    ADD attempts TINYINT UNSIGNED,
    ADD data_kind VARCHAR(16),
    ADD metadata_json LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin,
    ADD metadata_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin,
    ADD receipt_json LONGTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_bin,
    ADD receipt_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin,
    ADD registered_by VARCHAR(128),
    ADD registered_at DATETIME(6),
    ADD CHECK (attempts IS NULL OR attempts BETWEEN 1 AND 3),
    ADD CHECK (execution_mode IS NULL OR execution_mode IN ('api', 'manual_import')),
    ADD CHECK (data_kind IS NULL OR data_kind IN ('synthetic', 'real')),
    ADD CHECK (metadata_json IS NULL OR JSON_VALID(metadata_json)),
    ADD CHECK (receipt_json IS NULL OR JSON_VALID(receipt_json));
